/** Lucide icon by kebab-case name (see REGISTRY above); renders nothing for an unknown name. */
export function Icon({ name, size = 15, color, class: cls }: { name: string; size?: number; color?: string; class?: string }) {
  const Cmp = REGISTRY[name];
  if (!Cmp) return null;
  return <Cmp size={size} color={color} class={cls} strokeWidth={2} />;
}
